# Database Configuration
# Primary: MySQL database named 'smartcare_db' (host: localhost, port: 3306)
# Fallback: SQLite3 for offline local verification if MySQL server daemon is inactive
def is_mysql_reachable(host='localhost', port=3306, timeout=0.5):
    try:
        sock = socket.create_connection((host, int(port)), timeout=timeout)
        sock.close()
        return True
    except OSError:
        return False

FORCE_SQLITE = os.environ.get('FORCE_SQLITE', '0') == '1'

